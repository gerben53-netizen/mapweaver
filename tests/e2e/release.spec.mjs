import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import fs from 'node:fs/promises';
import { snapshot, model, point, clickMap, dragMap, capture, download, fixtures } from './helpers.mjs';
test('full editor workflow, recovery, portable projects, PNG pixels and keyboard UX', async ({ page, browser }) => {
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('/');
    await page.getByRole('button', { name: 'New', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'New project' });
    await dialog.getByLabel('Name', { exact: true }).fill('Release audit');
    await dialog.getByLabel('Width', { exact: true }).fill('800');
    await dialog.getByLabel('Height', { exact: true }).fill('600');
    await dialog.getByRole('button', { name: 'Create project' }).click();
    await capture(page, '01-editor-1280');
    await page.getByRole('tab', { name: 'Asset library', exact: true }).click();
    await page.getByLabel('New category', { exact: true }).fill('Audit');
    await page.getByRole('button', { name: 'Create category' }).click();
    await page.getByLabel('Import library assets').setInputFiles(`${fixtures}/stamp.png`);
    await page.getByRole('button', { name: /stamp.*64/ }).waitFor();
    await capture(page, '02-library-stamps');
    await page.getByRole('button', { name: /stamp.*64/ }).click();
    await page.getByLabel('Name', { exact: true }).fill('Audit chair');
    await page.getByRole('button', { name: 'Save details' }).click();
    await page.getByRole('searchbox').fill('chair');
    await expect(page.getByRole('button', { name: /Audit chair/ })).toBeVisible();
    await page.getByRole('searchbox').fill('');
    await page.getByRole('tab', { name: 'Fill patterns', exact: true }).click();
    await page.getByLabel('Import library assets').setInputFiles(`${fixtures}/fill.png`);
    await page.getByRole('button', { name: /fill.*32/ }).waitFor();
    await capture(page, '03-library-patterns');
    await page.getByRole('tab', { name: 'Map editor', exact: true }).click();
    const initial = model(await snapshot(page));
    const trigger = page.getByRole('button', { name: 'Place stamp', exact: true });
    await trigger.click();
    await expect(page.getByRole('searchbox')).toBeFocused();
    await page.getByRole('searchbox').fill('chair');
    await page.getByRole('dialog').getByRole('combobox', { name: 'Category', exact: true }).selectOption({ label: 'Audit' });
    await capture(page, '04-stamp-picker');
    await page.keyboard.press('Escape');
    await expect(trigger).toBeFocused();
    expect(model(await snapshot(page))).toEqual(initial);
    await trigger.click();
    await page.getByRole('button', { name: 'Choose Audit chair', exact: true }).dblclick();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await clickMap(page, 180, 180);
    await clickMap(page, 350, 180);
    expect((await snapshot(page)).objects).toHaveLength(2);
    await page.keyboard.press('Escape');
    await clickMap(page, 180, 180);
    await expect(page.getByRole('tab', { name: 'Properties', exact: true })).toHaveAttribute('aria-selected', 'true');
    await capture(page, '05-selected-stamp');
    await dragMap(page, 180, 180, 200, 210);
    let s = await snapshot(page);
    expect(s.objects[0].x).toBeCloseTo(168, 0);
    const corner = await point(page, s.objects[0].x + s.objects[0].width, s.objects[0].y + s.objects[0].height);
    await page.mouse.move(corner.x, corner.y);
    await page.mouse.down();
    await page.mouse.move(corner.x + 20, corner.y + 20, { steps: 8 });
    await page.mouse.up();
    expect((await snapshot(page)).objects[0].width).toBeGreaterThan(64);
    await page.getByRole('spinbutton', { name: 'Rotation (degrees)', exact: true }).fill('45');
    await page.getByRole('spinbutton', { name: 'Rotation (degrees)', exact: true }).press('Enter');
    await page.getByRole('button', { name: 'Flip horizontal' }).click();
    expect((await snapshot(page)).objects[0]).toMatchObject({ rotation: 45, scaleX: -1 });
    await page.getByRole('button', { name: 'Pattern fill', exact: true }).click();
    await capture(page, '06-pattern-picker');
    await page.getByRole('button', { name: 'Choose fill', exact: true }).dblclick();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await dragMap(page, 420, 320, 650, 480);
    expect((await snapshot(page)).objects[2].kind).toBe('patternFill');
    await capture(page, '07-selected-pattern');
    await page.getByRole('combobox', { name: 'Mode', exact: true }).selectOption('stretch');
    await page.getByRole('button', { name: 'Apply pattern settings' }).click();
    expect((await snapshot(page)).objects[2].mode).toBe('stretch');
    await page.getByRole('tab', { name: 'Layers', exact: true }).click();
    await page.getByRole('button', { name: 'Add layer', exact: true }).click();
    await page.getByRole('button', { name: 'Hide Layer 2' }).click();
    await page.getByRole('button', { name: 'Show Layer 2' }).click();
    await page.getByRole('button', { name: 'Lock Layer 2' }).click();
    await page.getByRole('button', { name: 'Unlock Layer 2' }).click();
    await page.getByRole('button', { name: 'Move Layer 2 down' }).click();
    await capture(page, '08-layers');
    await page.getByRole('tab', { name: 'Properties', exact: true }).click();
    await page.getByRole('button', { name: 'Duplicate', exact: true }).click();
    await page.getByRole('button', { name: 'Copy', exact: true }).click();
    await page.getByText('Edit', { exact: true }).click();
    await page.getByRole('button', { name: 'Paste objects' }).click();
    await page.getByText('Edit', { exact: true }).click();
    await page.getByRole('button', { name: 'Delete', exact: true }).click();
    const finalModel = model(await snapshot(page));
    const undoCount = (await snapshot(page)).history.undoCount;
    expect(undoCount).toBeGreaterThanOrEqual(10);
    for (let i = 0; i < undoCount; i++)
        await page.getByRole('button', { name: /^Undo:/ }).click();
    expect(model(await snapshot(page))).toEqual(initial);
    for (let i = 0; i < undoCount; i++)
        await page.getByRole('button', { name: /^Redo:/ }).click();
    expect(model(await snapshot(page))).toEqual(finalModel);
    await page.getByRole('button', { name: /^Undo:/ }).click();
    await page.getByRole('button', { name: 'Show grid', exact: true }).click();
    expect((await snapshot(page)).history.redoCount).toBe(0);
    await page.getByRole('tab', { name: 'Map', exact: true }).click();
    await capture(page, '09-map');
    await page.getByLabel('Width (px)', { exact: true }).fill('900');
    await page.getByRole('button', { name: 'Apply map settings' }).click();
    expect((await snapshot(page)).map.width).toBe(900);
    await page.getByRole('button', { name: 'Snap to grid', exact: true }).click();
    await page.keyboard.press('Alt');
    await page.keyboard.up('Alt'); // actual bypass is tested below with placement
    await page.getByRole('button', { name: 'Place stamp', exact: true }).click();
    await page.getByRole('button', { name: 'Choose Audit chair', exact: true }).last().dblclick();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await page.keyboard.down('Alt');
    await clickMap(page, 113, 111);
    await page.keyboard.up('Alt');
    await page.keyboard.press('Escape');
    expect((await snapshot(page)).objects.at(-1).x).toBeCloseTo(81, 0);
    const beforeRecovery = model(await snapshot(page));
    await expect(page.getByText('Unsaved changes · local copy saved', { exact: true })).toBeVisible({ timeout: 15000 });
    await page.reload();
    await page.getByRole('button', { name: 'Resume recovery' }).click();
    await expect.poll(async () => model(await snapshot(page))).toEqual(beforeRecovery);
    await capture(page, '10-recovery-resumed');
    page.once('dialog', d => d.dismiss());
    await page.getByRole('button', { name: 'New', exact: true }).click();
    await page.getByRole('button', { name: 'Create project' }).click();
    expect(model(await snapshot(page))).toEqual(beforeRecovery);
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    const path = await download(page, page.getByRole('button', { name: 'Download', exact: true }), '.audit.local/portable.mapweaver');
    expect((await snapshot(page)).history.dirty).toBe(false);
    const clean = await browser.newContext({ viewport: { width: 1920, height: 1080 } });
    const second = await clean.newPage();
    await second.goto('http://127.0.0.1:5180');
    await second.getByLabel('Mapweaver project file').setInputFiles(path);
    await expect.poll(async () => model(await snapshot(second))).toEqual(beforeRecovery);
    await capture(second, '11-editor-1920');
    await second.getByRole('button', { name: 'Place stamp', exact: true }).click();
    await second.getByRole('tab', { name: 'Project assets', exact: true }).click();
    await expect(second.getByRole('button', { name: 'Choose Audit chair' })).toBeVisible();
    await second.keyboard.press('Escape');
    await clean.close();
    const exportState = await snapshot(page);
    await page.getByRole('button', { name: 'Export PNG', exact: true }).click();
    const exp = page.getByRole('dialog', { name: 'Export PNG' });
    await exp.getByLabel('Include grid', { exact: true }).uncheck();
    for (const [scale, grid, transparent] of [[1, false, false], [2, true, false], [1, false, true]]) {
        await exp.getByRole('combobox', { name: 'Scale', exact: true }).selectOption(String(scale));
        await exp.getByLabel('Include grid', { exact: true }).setChecked(grid);
        await exp.getByLabel('Transparent canvas background', { exact: true }).setChecked(transparent);
        const file = await download(page, exp.getByRole('button', { name: 'Download PNG', exact: true }), `.audit.local/export-${scale}-${transparent}.png`);
        const bytes = await fs.readFile(file);
        expect(bytes.readUInt32BE(16)).toBe(900 * scale);
        expect(bytes.readUInt32BE(20)).toBe(600 * scale);
        const pixel = await page.evaluate(async (data) => { const blob = new Blob([Uint8Array.from(data)], { type: 'image/png' }), im = await createImageBitmap(blob), c = new OffscreenCanvas(im.width, im.height), ctx = c.getContext('2d'); ctx.drawImage(im, 0, 0); const p = Array.from(ctx.getImageData(im.width - 1, im.height - 1, 1, 1).data); im.close(); return p; }, [...bytes]);
        if (transparent)
            expect(pixel[3]).toBe(0);
        else
            expect(pixel[3]).toBe(255);
        await expect(exp.locator('pre')).toContainText(`${900 * scale} × ${600 * scale}`);
    }
    await exp.getByRole('button', { name: 'Close', exact: true }).click();
    expect(model(await snapshot(page))).toEqual(model(exportState));
    expect((await snapshot(page)).history).toEqual(exportState.history);
    const axe = await new AxeBuilder({ page }).analyze();
    await fs.writeFile('.audit.local/axe-editor.json', JSON.stringify(axe.violations, null, 2));
    expect(axe.violations.filter(v => v.impact === 'critical')).toEqual([]);
    await page.getByLabel('Mapweaver project file').setInputFiles(`${fixtures}/malicious.mapweaver`);
    await expect(page.getByRole('alert')).toContainText(/unsafe|Invalid/);
    expect(model(await snapshot(page))).toEqual(model(exportState));
    await capture(page, '12-invalid-file');
    expect(errors).toEqual([]);
});
